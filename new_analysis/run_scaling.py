"""Task B: scaling of the vector-to-human ratio Nv/Nh.

All other parameters at baseline; Nv/Nh in {1,2,3,5,10,15,20}; baseline
scenario (seasonal temperature + import pulse), 1095 days.

Motivation: how the "peak Ih = 1,650" headline number scales with the assumed
vector density.
"""

import os
import sys
import time

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'src'))
sys.path.insert(0, HERE)

import dv_common as C
import model as M
import r0 as R0

SEED = 20260816
NV_VALUES = [1, 2, 3, 5, 10, 15, 20]


def main():
    t_start = time.perf_counter()
    C.reset_rates()

    # timing of a single solve
    t0 = time.perf_counter()
    C.run_case(M.baseline_params())
    per_run = time.perf_counter() - t0

    rows = []
    for nv in NV_VALUES:
        p = M.baseline_params(nv_ratio=float(nv))
        m = C.run_case(p)
        r0_28 = R0.compute_r0(p, 28.0)
        r0_season_mean = float(np.mean([
            R0.compute_r0(p, T) for T in
            [M.seasonal_temperature(t) for t in range(0, 365)]
        ]))
        rows.append({
            'nv_ratio': float(nv),
            'peak_ih': m['peak_ih'],
            'peak_ih_per_10000_humans': m['peak_ih'],
            'peak_day': m['peak_day'],
            'cum_infected': m['cum_infected'],
            'cum_check': m['cum_check'],
            'R0_at_28C': float(r0_28),
            'R0_seasonal_mean_year1': r0_season_mean,
        })
        print(f"Nv/Nh={nv:<3} peak={m['peak_ih']:9.1f} "
              f"day={m['peak_day']:7.1f} cum={m['cum_infected']:.4f} "
              f"R0(28)={r0_28:.2f}")

    base = next(r for r in rows if r['nv_ratio'] == 10.0)
    for r in rows:
        r['peak_ratio_to_nv10'] = r['peak_ih'] / base['peak_ih']
        r['peak_pct_change_vs_nv10'] = 100.0 * (r['peak_ih'] / base['peak_ih'] - 1.0)

    wall = time.perf_counter() - t_start

    payload = {
        'task': 'B - Nv/Nh scaling of the baseline-scenario outputs',
        'method': (
            'Baseline scenario (seasonal T(t)=22+7.8cos(2pi(t-200)/365) and '
            'annual import pulse), all parameters at baseline except '
            'nv_ratio; model.solve, t_span=(0,1095), daily output.'
        ),
        'note_Nh': (
            'Nh = 10,000 throughout, so peak_ih is directly the peak number '
            'of infectious humans for a 10,000-person population; '
            'peak_ih/10000 is the peak prevalence.'
        ),
        'rows': rows,
        'meta': C.make_meta(
            script='run_scaling.py', seed=SEED, n_samples=len(NV_VALUES),
            wall_seconds=wall, per_run_seconds=per_run,
            extra={'nv_values': NV_VALUES,
                   'n_ode_solves': len(NV_VALUES) + 1}
        ),
    }
    C.write_json(os.path.join(HERE, 'nv_scaling.json'), payload)

    # ── markdown table ──────────────────────────────────────────────────────
    lines = [
        '# Nv/Nh scaling of the baseline scenario',
        '',
        'Baseline scenario, Nh = 10,000, 1095 days, all other parameters at baseline.',
        '',
        '| Nv/Nh | peak Ih | peak prevalence | peak day | 3-yr cumulative infection | '
        'R0 (28 °C) | peak vs Nv/Nh=10 |',
        '|---:|---:|---:|---:|---:|---:|---:|',
    ]
    for r in rows:
        lines.append(
            f"| {r['nv_ratio']:.0f} | {r['peak_ih']:.0f} | "
            f"{r['peak_ih'] / 10000:.2%} | {r['peak_day']:.0f} | "
            f"{r['cum_infected']:.2%} | {r['R0_at_28C']:.2f} | "
            f"{r['peak_pct_change_vs_nv10']:+.1f}% |"
        )
    lines += [
        '',
        f"Generated by `run_scaling.py` (seed {SEED}) on "
        f"{payload['meta']['run_date_local']}.",
    ]
    md_path = os.path.join(HERE, 'nv_scaling.md')
    with open(md_path, 'w', encoding='utf-8') as fh:
        fh.write('\n'.join(lines) + '\n')
    print(f"[written] {md_path}")


if __name__ == '__main__':
    main()
